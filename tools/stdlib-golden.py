"""Regenerate independent reference cases with CPython 3.13 (no mod imports).

Run from the repository root: python tools/stdlib-golden.py.
The random reference is the original pure Python xorshift64 implementation,
not CPython's unrelated Mersenne Twister.
"""
import io
import json
import platform
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'src/test/resources'


def save(name, lines):
    header = '# Generated by tools/stdlib-golden.py on CPython ' + platform.python_version()
    (ROOT / ('stdlib-' + name + '-golden.py')).write_text('\n'.join([header] + lines + ['passed = True', '']), encoding='utf-8')


def json_cases():
    lines = ['import json']
    valid = ['null', 'true', 'false', '0', '-0', '123456789012345678901234567890', '1.25', '-2e-3',
             ' [1, true, null, {"x": "\\n\\t\\b\\f\\r\\\\\\/\\\""}] ', '{"a":1,"a":2}',
             '"\\ud83d\\ude00"', '"\\ud800"', '"\\udfff"', '"\\ud800x"', '"\\ud800\\u0041"',
             '"water 水"', '\r\n {"empty": [], "obj": {}}\t']
    for text in valid:
        expected = json.loads(text)
        # The VM's .mpy UTF-8 string loader replaces lone surrogates in source
        # literals. Construct those reference values at runtime instead.
        expr = ascii(expected)
        if isinstance(expected, str) and any(0xd800 <= ord(c) <= 0xdfff for c in expected):
            expr = "''.join([chr(n) for n in %r])" % [ord(c) for c in expected]
        lines.append('assert json.loads(%s) == %s, %s' % (ascii(text), expr, ascii(text)))
    invalid = ['', ' ', '+1', '01', '-01', '-', '1.', '1e', '1e+', 'True', 'None', 'null false',
               '\v1', '{', '{a:1}', '{"a" 1}', '{"a":}', '{"a":1', '{"a":1,}', '[', '[1 2]', '[1,]',
               '"abc', '"abc\\', '"\\x"', '"\\uZZZZ"', '"\\u12"', '"\\u１２３４"', '"a\nb"',
               '[\n 1,\n ?]', '"😀" x', '{"😀": ?}', '["😀",\n?]', '\ufeff{}']
    for text in invalid:
        try:
            json.loads(text)
        except json.JSONDecodeError as e:
            expected = (e.msg, e.pos, e.lineno, e.colno, str(e))
        else:
            raise AssertionError(text)
        lines += ['try:', '    json.loads(%s)' % ascii(text), "    raise AssertionError('accepted invalid JSON')",
                  'except json.JSONDecodeError as e:',
                  '    assert (e.msg, e.pos, e.lineno, e.colno, str(e)) == %s, (e.msg, e.pos, e.lineno, e.colno, str(e))' % ascii(expected),
                  '    assert e.doc == %s' % ascii(text)]
    objects = [None, True, False, 0, -4, 10**40, 0.0, -0.0, 1e-5, 1e20, 1e23, 5e-324,
               '水😀\x00\x7f\n\\"', [], {}, [1, {'z': [None, True], 'a': {}}],
               {'b': 2, 'a': 1}, {10: 'ten', 2: 'two', -1: 'negative'}, {False: 0, True: 1},
               {'\ue000': 1, '😀': 2}, {(1, 2): 'skip'}, {None: 'nil'}]
    options = [{}, {'indent': 2}, {'indent': '\t'}, {'indent': 0}, {'indent': -2}, {'indent': True},
               {'separators': (',', ':')}, {'ensure_ascii': False}, {'sort_keys': True, 'skipkeys': True}]
    for obj in objects:
        for kw in options:
            kw = dict(kw, skipkeys=True)
            expr = 'json.dumps(%s, **%s)' % (ascii(obj), ascii(kw))
            lines.append('assert %s == %s, (%s, %s)' % (expr, ascii(json.dumps(obj, **kw)), ascii(expr), expr))
    save('json', lines)


def io_cases():
    lines = ['import io']
    for name in ['StringIO', 'BytesIO']:
        binary = name == 'BytesIO'
        data = (lambda s: s.encode()) if binary else (lambda s: s)
        stream = getattr(io, name)(data('abc\ndef\n'))
        lines.append('f = io.%s(%s)' % (name, ascii(data('abc\ndef\n'))))
        actions = [('read', (2,)), ('readline', ()), ('readlines', ()), ('seek', (0,)),
                   ('write', (data('XY'),)), ('seek', (0, 2)), ('write', (data('tail'),)),
                   ('seek', (30,)), ('read', ()), ('readline', ()), ('write', (data(''),)),
                   ('write', (data('!'),)), ('truncate', (4,)), ('read', ()), ('seek', (0,)), ('read', ()),
                   ('truncate', (20,)), ('seek', (0, 2)), ('write', (data('++'),)), ('seek', (0,)),
                   ('readline', (2,)), ('read', (None,)), ('seek', (-2, 1)), ('seek', (-2, 2)),
                   ('seek', (-100, 1)), ('seek', (-1,)), ('seek', (0, 3)), ('truncate', (-1,)),
                   ('read', (1.5,)), ('seek', (1.5,)), ('truncate', (1.5,)), ('close', ()),
                   ('read', ()), ('write', (data(''),)), ('getvalue', ()), ('seek', (0,)), ('tell', ()),
                   ('truncate', ()), ('readable', ()), ('writable', ()), ('seekable', ()), ('flush', ()),
                   ('writelines', ([],))]
        for method, args in actions:
            expr = 'f.%s(%s)' % (method, ', '.join(ascii(a) for a in args))
            try:
                result = getattr(stream, method)(*args)
            except Exception as e:
                lines += ['try:', '    ' + expr, "    raise AssertionError('expected an error')",
                          'except %s:' % type(e).__name__, '    pass']
            else:
                lines.append('assert %s == %s, %s' % (expr, ascii(result), ascii(expr)))
            if not stream.closed:
                lines.append('assert (f.tell(), f.getvalue()) == %s, (f.tell(), f.getvalue())' % ascii((stream.tell(), stream.getvalue())))
    save('io', lines)


def random_cases():
    mask = (1 << 64) - 1
    lines = ['import random']
    for seed in [0, 1, -1, 88172645463325252, 1 << 63, 10**60]:
        state = seed & mask or 88172645463325252
        def step():
            nonlocal state
            state = (state ^ (state << 13)) & mask
            state ^= state >> 7
            state = (state ^ (state << 17)) & mask
            return state
        lines.append('random.seed(%s)' % seed)
        for _ in range(4):
            for bits in [1, 7, 32, 53, 63, 64]:
                lines.append('assert random.getrandbits(%s) == %s' % (bits, step() >> (64 - bits)))
            for lo, hi in [(0, 10), (-100, 100), (0, 1 << 63), (0, 10**30)]:
                lines.append('assert random.randrange(%s, %s) == %s' % (lo, hi, lo + step() % (hi - lo)))
            lines.append('assert random.random() == %r' % ((step() >> 11) * (1.0 / 9007199254740992.0)))
    save('random', lines)


if __name__ == '__main__':
    json_cases()
    io_cases()
    random_cases()
