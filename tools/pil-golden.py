"""Regenerate deterministic Pillow reference cases; Pillow is test-only.

python -m pip install --target build/pillow-reference Pillow==12.0.0
python tools/pil-golden.py
"""
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build/pillow-reference'))
from PIL import Image, ImageColor, ImageDraw, ImageOps, __version__

assert __version__ == '12.0.0', __version__
# Pillow caches parsed tuples in this public dict while getrgb runs below.
# Keep the exported CSS table separate from that cache.
css_names = ImageColor.colormap.copy()
out = ["# Generated by tools/pil-golden.py with Pillow " + __version__,
       "from PIL import Image, ImageColor, ImageDraw, ImageOps", "import io"]
scope = dict(Image=Image, ImageColor=ImageColor, ImageDraw=ImageDraw, ImageOps=ImageOps, io=io)
cases = 0


def setup(code):
    exec(code, scope)
    out.append(code)


def check(expr):
    global cases
    value = eval(expr, scope)
    out.append(f'assert {expr} == {value!r}, {expr!r}')
    cases += 1


def pixels(expr, tolerance=0):
    global cases
    im = eval(expr, scope)
    out.append('result = ' + expr)
    out.append(f'assert result.size == {im.size!r} and result.mode == {im.mode!r}, {expr!r}')
    expected = im.tobytes()
    if tolerance:
        out.append(f'assert max([abs(a-b) for a,b in zip(result.tobytes(), {expected!r})]) <= {tolerance}, {expr!r}')
    else:
        out.append(f'assert result.tobytes() == {expected!r}, {expr!r}')
    cases += 1


for mode in ('L', 'RGB', 'RGBA'):
    setup(f"im = Image.frombytes({mode!r}, (5, 3), bytes((i * 37 + 11) % 256 for i in range({15 * len(mode)})))")
    pixels('im.copy()')
    for target in ('L', 'RGB', 'RGBA'):
        pixels(f'im.convert({target!r})')
    for method in range(7):
        pixels(f'im.transpose({method})')
    for box in ((1, 1, 4, 3), (-1, -2, 6, 4)):
        pixels(f'im.crop({box!r})')
    for method in range(6):
        pixels(f'im.resize((3, 2), {method})', 1 if method else 0)
        pixels(f'im.resize((8, 6), {method})', 1 if method else 0)
        pixels(f'im.resize(im.size, {method})')
    check('list(im.getdata())')
    check('im.getpixel((-1, -1))')
    check('im.histogram()')
    for channel in range(len(mode)):
        pixels(f'im.getchannel({channel})')
    setup('mask = Image.frombytes("L", (5, 3), bytes((i * 17) % 256 for i in range(15)))')
    setup('dst = Image.new(im.mode, (7, 5), 91)\ndst.paste(im, (1, 1), mask)')
    pixels('dst')
    setup('dst.paste(im, (-2, -1), mask)')
    pixels('dst')
    setup('dst.paste(33, (0, 0, 2, 3))')
    pixels('dst')
    setup('dst.paste(dst, (1, 1))')
    pixels('dst')
    for method in ('flip', 'mirror', 'grayscale'):
        pixels(f'ImageOps.{method}(im)')
    for method in ('contain', 'cover', 'pad'):
        pixels(f'ImageOps.{method}(im, (7, 7), Image.NEAREST)')
    pixels('ImageOps.crop(ImageOps.expand(im, (1, 2, 3, 4)), (1, 2, 3, 4))')
    pixels('Image.blend(im, Image.new(im.mode, im.size, 111), 0.35)')
    setup('buf = io.BytesIO()\nim.save(buf, format="PNG")\nbuf.seek(0)')
    pixels('Image.open(buf)')
    if mode != 'RGBA':
        for operation in ('invert(im)', 'posterize(im, 3)', 'solarize(im, 100)'):
            pixels('ImageOps.' + operation)

setup('a = Image.new("RGBA", (3, 2), (90, 20, 220, 137))\nb = Image.new("RGBA", (3, 2), (5, 230, 70, 191))')
pixels('Image.alpha_composite(a, b)')
for da, sa in [(0, 0), (0, 255), (255, 0), (1, 1), (127, 128), (254, 254)]:
    pixels(f'Image.alpha_composite(Image.new("RGBA", (1, 1), (12, 53, 170, {da})), Image.new("RGBA", (1, 1), (197, 33, 1, {sa})))')
setup('a.putalpha(71)')
pixels('a')
setup('a.putalpha(Image.new("L", a.size, 209))')
pixels('a')
for mode, fill, outline in [('L', 71, 209), ('RGB', '#a29f43', 'blue'), ('RGBA', '#a29f435b', '#314abbcc')]:
    setup(f'im = Image.new({mode!r}, (11, 9))\ndraw = ImageDraw.Draw(im)')
    setup(f'draw.rectangle((1, 2, 9, 7), fill={fill!r}, outline={outline!r}, width=2)')
    pixels('im')
    setup(f'draw.point([(0, 0), (10, 8), (-1, 0)], fill={fill!r})')
    pixels('im')
    setup('draw.point((3, 3))\ndraw.rectangle((4, 1, 8, 5))\ndraw.line((0, 8, 10, 8))')
    pixels('im')

out.append('color_cases = [')
for color in list(ImageColor.colormap) + ['#abc', '#abcd', '#123456', '#12345678', 'rgb(12, 33, 255)', 'rgba(12, 33, 255, 77)', 'rgb(10%, 20%, 100%)', 'hsl(120, 50%, 25%)', 'hsv(245, 70%, 90%)']:
    row = (color, ImageColor.getrgb(color)) + tuple(ImageColor.getcolor(color, mode) for mode in ('L', 'RGB', 'RGBA'))
    out.append('    ' + repr(row) + ',')
    cases += 4
out.extend([']', 'for color, rgb, gray, opaque, alpha in color_cases:',
            '    assert ImageColor.getrgb(color) == rgb, color',
            '    assert ImageColor.getcolor(color, "L") == gray, color',
            '    assert ImageColor.getcolor(color, "RGB") == opaque, color',
            '    assert ImageColor.getcolor(color, "RGBA") == alpha, color'])

out.append('passed = True')
(ROOT / 'src/test/resources/stdlib-pil-golden.py').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'{cases} Pillow golden comparisons written')

colors = ROOT / 'stdlib/PIL/ImageColor.py'
prefix = colors.read_text(encoding='utf-8').split('colormap = ', 1)[0]
colors.write_text(prefix + 'colormap = ' + repr(css_names) + '\n', encoding='utf-8')

# Tiny independent encoded fixtures, including grayscale and palette inputs.
fixtures = ROOT / 'src/test/resources/pil'
fixtures.mkdir(exist_ok=True)
for mode in ('L', 'RGB', 'RGBA'):
    im = Image.frombytes(mode, (5, 3), bytes((i * 37 + 11) % 256 for i in range(15 * len(mode))))
    for fmt in ('PNG', 'JPEG', 'GIF', 'BMP'):
        if mode == 'RGBA' and fmt != 'PNG':
            continue
        path = fixtures / f'{mode.lower()}.{fmt.lower()}'
        im.save(path)
        decoded = Image.open(path).convert(mode)
        path.with_suffix(path.suffix + '.raw').write_bytes(decoded.tobytes())
